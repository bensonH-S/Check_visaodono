function normCod(c) {
  return String(c || '').trim().toUpperCase();
}

export function codigosDoTipo(tipo) {
  if (tipo === 'desperdicio_completo') return CODIGOS_DC;
  if (tipo === 'desperdicio_incompleto') return CODIGOS_DI;
  if (tipo === 'emprestimo') return CODIGOS_EMPRESTIMO;
  return CODIGOS_BREAK; // refeicao / break / outro
}

export function filtrarPorCodigos(rows, tipo) {
  const set = new Set(codigosDoTipo(tipo).map(normCod));
  return (rows || []).filter((row) => set.has(normCod(row.codigo)));
}
